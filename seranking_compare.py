#!/usr/bin/env python3
"""Compare two SE Ranking snapshots (audits/seranking-YYYY-MM-DD dirs).

Reproduces the structure of the hand-made comparison-vs-* reports:
  1. keywords / position buckets / traffic overview (+ trend anchor month)
  2. backlinks delta
  3. money-keyword movers (families from config/competitors.json)
  4. locale-leak trend (/de/ URLs)
  5. anomalies & caveats

Absence of a keyword in the newer snapshot is labeled `LOST (top-100)` only
when meta.json says the keyword pull was complete; otherwise
`LOST (pull-truncated — verify)` — old capped pulls can't distinguish the two.

Outputs into the newer snapshot dir:
  comparison-vs-<baseline>.md
  movers.csv

Usage:
  python3 seranking_compare.py                      # two most recent snapshots
  python3 seranking_compare.py --date 2026-09-01 --baseline 2026-08-16
"""

import argparse
import csv
import json
import re
from pathlib import Path
from urllib.parse import urlparse

REPO = Path(__file__).parent
CONFIG = REPO / "config" / "competitors.json"


def snapshot_dirs():
    return sorted(REPO.glob("audits/seranking-????-??-??"))


def load_json(path):
    if not path.exists():
        return None
    data = json.load(open(path))
    return data


def overview_organic(raw):
    o = load_json(raw / "overview_ch.json")
    if o is None:
        return None
    if isinstance(o, list):
        o = o[0]
    return o.get("organic", o)


def path_of(url):
    return urlparse(url).path or "/"


def family_matchers(families):
    """Word-boundary regex for short single-word families (avoids 'uid' in
    'guide'), plain substring for the rest."""
    matchers = []
    for fam in families:
        if len(fam) <= 5 and " " not in fam:
            rx = re.compile(rf"\b{re.escape(fam)}\b", re.I)
            matchers.append((fam, lambda k, rx=rx: bool(rx.search(k))))
        else:
            matchers.append((fam, lambda k, fam=fam.lower(): fam in k))
    return matchers


def best_positions(rows):
    """keyword -> best-position row."""
    best = {}
    for r in rows:
        if not r.get("position"):
            continue
        k = r["keyword"].lower()
        if k not in best or r["position"] < best[k]["position"]:
            best[k] = r
    return best


def fmt_delta(old, new):
    if old is None or new is None:
        return ""
    d = new - old
    return f"+{d:,}" if d > 0 else f"{d:,}"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--date", default=None, help="newer snapshot date (default: latest)")
    ap.add_argument("--baseline", default=None, help="older snapshot date (default: second latest)")
    ap.add_argument("--top", type=int, default=40, help="rows in the main movers table")
    args = ap.parse_args()

    dirs = snapshot_dirs()
    if args.date:
        new_dir = REPO / "audits" / f"seranking-{args.date}"
    else:
        new_dir = dirs[-1]
    if args.baseline:
        base_dir = REPO / "audits" / f"seranking-{args.baseline}"
    else:
        older = [d for d in dirs if d.name < new_dir.name]
        if not older:
            raise SystemExit("no baseline snapshot found")
        base_dir = older[-1]
    new_date = new_dir.name.replace("seranking-", "")
    base_date = base_dir.name.replace("seranking-", "")
    new_raw, base_raw = new_dir / "raw", base_dir / "raw"
    print(f"comparing {new_date} vs baseline {base_date}")

    cfg = json.load(open(CONFIG))
    families = cfg.get("money_keyword_families", [])

    lines = [
        f"# SE Ranking Snapshot Comparison — magicheidi.ch (CH database)",
        "",
        f"**Snapshot date:** {new_date} · **Baseline:** {base_date} (`{base_raw.relative_to(REPO)}/`)",
        "",
        f"Raw data: `{new_raw.relative_to(REPO)}/`. Generated by `seranking_compare.py`.",
    ]

    # ---- 1. Overview
    new_org, base_org = overview_organic(new_raw), overview_organic(base_raw)
    anchor_label, anchor = None, None
    hist = load_json(new_raw / "overview_history_ch.json") or load_json(base_raw / "overview_history_ch.json")
    if hist:
        base_ym = (int(base_date[:4]), int(base_date[5:7]))
        before = [h for h in hist if (h["year"], h["month"]) < base_ym]
        if before:
            anchor = max(before, key=lambda h: (h["year"], h["month"]))
            anchor_label = f"{anchor['year']}-{anchor['month']:02d}"
    if new_org and base_org:
        lines += ["", "## 1. Keywords, buckets, traffic", ""]
        hdr = "| Metric |"
        sep = "|---|"
        if anchor:
            hdr += f" {anchor_label} |"
            sep += "---:|"
        hdr += f" {base_date} | {new_date} | Δ vs baseline |"
        sep += "---:|---:|---:|"
        lines += [hdr, sep]
        metrics = [
            ("Total CH keywords", "keywords_count"),
            ("Top 1–5", "top1_5"), ("Top 6–10", "top6_10"), ("Top 11–20", "top11_20"),
            ("Top 21–50", "top21_50"), ("Top 51–100", "top51_100"),
            ("Est. traffic (traffic_sum)", "traffic_sum"),
            ("Traffic value (price_sum)", "price_sum"),
        ]
        for label, key in metrics:
            row = f"| {label} |"
            if anchor:
                row += f" {anchor.get(key, ''):,} |" if isinstance(anchor.get(key), (int, float)) else " – |"
            b, n = base_org.get(key), new_org.get(key)
            row += f" {b:,} | {n:,} | {fmt_delta(b, n)} |"
            lines.append(row)
        nl = new_org
        lines += ["", f"New/lost (overview month-over-month counters, {new_date} snapshot): "
                  f"**{nl.get('keywords_new_count', 0):,} new / {nl.get('keywords_lost_count', 0):,} lost / "
                  f"{nl.get('keywords_up_count', 0):,} up / {nl.get('keywords_down_count', 0):,} down**."]
    else:
        lines += ["", "## 1. Keywords, buckets, traffic", "", "_overview_ch.json missing in one snapshot — skipped_"]

    # ---- 2. Backlinks
    def bl_metrics(raw):
        s = load_json(raw / "backlinks_summary.json")
        a = load_json(raw / "backlinks_authority.json")
        if not s:
            return None
        m = dict(s["summary"][0])
        if a and a.get("pages"):
            m["inlink_rank"] = a["pages"][0].get("inlink_rank")
            m["domain_inlink_rank"] = a["pages"][0].get("domain_inlink_rank")
        return m

    nb, bb = bl_metrics(new_raw), bl_metrics(base_raw)
    lines += ["", "## 2. Backlinks", ""]
    if nb and bb:
        lines += [f"| Metric | {base_date} | {new_date} | Δ |", "|---|---:|---:|---:|"]
        for label, key in [("Backlinks", "backlinks"), ("Referring domains", "refdomains"),
                           ("Dofollow backlinks", "dofollow_backlinks"),
                           ("Dofollow refdomains", "dofollow_refdomains"),
                           ("Domain Trust (domain_inlink_rank)", "domain_inlink_rank"),
                           ("Page Trust homepage (inlink_rank)", "inlink_rank")]:
            b, n = bb.get(key), nb.get(key)
            if b is None and n is None:
                continue
            lines.append(f"| {label} | {b:,} | {n:,} | {fmt_delta(b, n)} |")
    else:
        lines.append("_backlinks_summary.json missing in one snapshot — skipped_")

    # ---- 3 + 4 + 5 need keyword rows
    new_kw_rows = load_json(new_raw / "keywords_ch.json")
    base_kw_rows = load_json(base_raw / "keywords_ch.json")
    movers_csv_rows = []
    if new_kw_rows and base_kw_rows:
        new_meta = load_json(new_raw / "meta.json") or {}
        new_complete = bool(new_meta.get("pulls", {}).get("keywords_ch", {}).get("complete"))
        lost_label = "LOST (top-100)" if new_complete else "LOST (pull-truncated — verify)"

        matchers = family_matchers(families)

        def is_money(kw):
            return any(m(kw) for _, m in matchers)

        new_best, base_best = best_positions(new_kw_rows), best_positions(base_kw_rows)
        money_keys = {k for k in set(new_best) | set(base_best) if is_money(k)}
        movers = []
        for k in money_keys:
            nrow, brow = new_best.get(k), base_best.get(k)
            vol = max((r.get("volume") or 0) for r in (nrow, brow) if r)
            npos = nrow["position"] if nrow else None
            bpos = brow["position"] if brow else None
            if npos and bpos:
                delta, note = bpos - npos, ""
                if bpos - npos >= 3:
                    note = f"+{bpos - npos}"
                elif npos - bpos >= 3:
                    note = f"−{npos - bpos}"
            elif npos:
                delta, note = 0, "NEW"
            else:
                delta, note = 0, lost_label
            movers.append({
                "keyword": (nrow or brow)["keyword"], "volume": vol,
                "pos_baseline": bpos or "", "pos_now": npos or "",
                "url_now": path_of(nrow["url"]) if nrow else "",
                "note": note, "_delta": abs(delta) if npos and bpos else 0,
            })
        movers.sort(key=lambda r: -r["volume"])
        lines += ["", f"## 3. Money-keyword movers ({base_date} → {new_date})", "",
                  f"Families matched ({len(families)} from config): " + ", ".join(families) + ".",
                  f"{len(money_keys)} matching keywords (best position per keyword). Top {args.top} by volume:",
                  "",
                  f"| Keyword | Vol | {base_date} | {new_date} | URL now | Note |",
                  "|---|---:|---:|---:|---|---|"]
        for r in movers[:args.top]:
            lines.append(f"| {r['keyword']} | {r['volume']:,} | {r['pos_baseline'] or '–'} | "
                         f"{r['pos_now'] or '–'} | {r['url_now']} | {r['note']} |")
        extra = [r for r in movers[args.top:] if r["volume"] >= 100 and
                 (r["_delta"] >= 3 or r["note"] in ("NEW",) or r["note"].startswith("LOST"))]
        if extra:
            lines += ["", "Additional movers (vol ≥ 100, |Δ| ≥ 3 or NEW/LOST): " +
                      "; ".join(f"{r['keyword']} {r['pos_baseline'] or '–'}→{r['pos_now'] or '–'}"
                                for r in extra[:40]) + "."]
        movers_csv_rows = movers

        # ---- 4. Locale leaks
        def leak_counts(rows):
            any_pos = sum(1 for r in rows if "/de/" in path_of(r.get("url", "")))
            top30 = sum(1 for r in rows if "/de/" in path_of(r.get("url", ""))
                        and r.get("position") and r["position"] <= 30)
            return any_pos, top30

        b_any, b_30 = leak_counts(base_kw_rows)
        n_any, n_30 = leak_counts(new_kw_rows)
        lines += ["", "## 4. Locale-leak check (/de/ URLs)", "",
                  "Method: keyword rows whose ranking URL contains `/de/`, same method on both snapshots.",
                  "",
                  f"| Metric | {base_date} | {new_date} | Δ |", "|---|---:|---:|---:|",
                  f"| Rows ranking with /de/ URL (any position) | {b_any:,} | {n_any:,} | {fmt_delta(b_any, n_any)} |",
                  f"| Rows ranking with /de/ URL in top-30 | {b_30:,} | {n_30:,} | {fmt_delta(b_30, n_30)} |"]

        # ---- 5. Anomalies
        lines += ["", "## 5. Anomalies & caveats", ""]
        big_drops = [r for r in movers if r["pos_now"] and r["pos_baseline"]
                     and r["volume"] >= 300 and (r["pos_now"] - r["pos_baseline"]) >= 5]
        big_drops.sort(key=lambda r: -(r["pos_now"] - r["pos_baseline"]))
        for r in big_drops[:10]:
            lines.append(f"- **{r['keyword']}** (vol {r['volume']:,}) dropped "
                         f"{r['pos_baseline']} → {r['pos_now']} on {r['url_now']}")
        lost_1s = [r for r in movers if r["pos_baseline"] == 1 and r["pos_now"] != 1
                   and r["volume"] >= 50]
        for r in lost_1s[:15]:
            lines.append(f"- Former #1 **{r['keyword']}** (vol {r['volume']:,}) now at "
                         f"{r['pos_now'] or 'not found'}")
        if not new_complete:
            lines.append("- Keyword pull completeness unknown/truncated for the newer snapshot — "
                         "absent keywords may have fallen below the pull cutoff, not out of Google; "
                         "spot-check LOST rows manually.")
        lines.append("- Position buckets sum to more than keywords_count (SE Ranking counts "
                     "keyword-URL pairs in buckets); comparisons stay consistent since the same "
                     "definition applies to all dates.")
    else:
        lines += ["", "## 3–5. Keyword sections", "", "_keywords_ch.json missing in one snapshot — skipped_"]

    out_md = new_dir / f"comparison-vs-{base_date}.md"
    out_md.write_text("\n".join(lines) + "\n")
    print(f"wrote {out_md}")
    if movers_csv_rows:
        out_csv = new_dir / "movers.csv"
        with open(out_csv, "w", newline="") as f:
            w = csv.DictWriter(f, fieldnames=["keyword", "volume", "pos_baseline",
                                              "pos_now", "url_now", "note"],
                               extrasaction="ignore")
            w.writeheader()
            w.writerows(movers_csv_rows)
        print(f"wrote {out_csv} ({len(movers_csv_rows)} rows)")


if __name__ == "__main__":
    main()
